import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base


class Artifact(Base):
    """A generated study artifact for a Collection (Create tab / artifact studio).

    kind ∈ {quiz, paper, audio, info}. Content shape depends on kind:
      quiz  → {"questions": [{"q","options":[4],"answer":int,"why"}]}
      paper → {"markdown": "...", "outline": ["..."]}
    (audio/info land in later passes.) Generated by an open-source Fireworks
    model — see ai/pipeline.py generate_quiz / generate_paper.
    """

    __tablename__ = "artifacts"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    collection_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("collections.id", ondelete="CASCADE"), nullable=False, index=True
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    kind: Mapped[str] = mapped_column(String(16), nullable=False)
    title: Mapped[str] = mapped_column(String(300), nullable=False, default="")
    # "ready" | "failed" — generation is synchronous, so rows are created ready.
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="ready")
    content: Mapped[dict | None] = mapped_column(JSONB, default=dict)
    model: Mapped[str | None] = mapped_column(String(120))
    error: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), index=True
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
